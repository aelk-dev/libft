#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*p;
	int		i;

	p = malloc(ft_strlen(s) + 1 * sizeof(const char));
	if (p == NULL)
		return (NULL);
	i = 0;
	while (s[i] != '\0')
	{
		p[i] = s[i];
		i++;
	}
	p[i] = '\0';
	return (p);
}
